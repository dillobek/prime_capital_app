const Map<AppLocale, Map<String, String>> _dict = {
  AppLocale.uz: _uz,
  AppLocale.ru: _ru,
  AppLocale.ar: _ar,
  AppLocale.en: _en,
};

/// Holds the current locale and notifies listeners on change; persists the
/// choice so the app reopens in the same language.
class LangController extends ChangeNotifier {
  AppLocale _locale = AppLocale.uz;
  AppLocale get locale => _locale;

  static const _prefsKey = 'prime_mobile_locale';

  Future<void> restore() async {
    final prefs = await SharedPreferences.getInstance();
    _locale = AppLocaleLabel.fromCode(prefs.getString(_prefsKey));
    notifyListeners();
  }

  Future<void> setLocale(AppLocale locale) async {
    if (locale == _locale) return;
    _locale = locale;
    notifyListeners();
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefsKey, locale.code);
  }

  String t(String key) => _dict[_locale]?[key] ?? _dict[AppLocale.uz]?[key] ?? key;
}

/// Exposes [LangController] to the widget tree and rebuilds descendants
/// whenever the locale changes.
class LangScope extends InheritedNotifier<LangController> {
  const LangScope({super.key, required LangController controller, required super.child})
      : super(notifier: controller);

  static LangController of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<LangScope>();
    assert(scope != null, 'LangScope not found in context');
    return scope!.notifier!;
  }
}

/// Shorthand used throughout the screens: `t(context, 'wa.nav.home')`.
String t(BuildContext context, String key) => LangScope.of(context).t(key);
