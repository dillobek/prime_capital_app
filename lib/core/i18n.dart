/// Lightweight in-house i18n, deliberately mirroring the structure and key
/// names of Webapp's `src/lib/i18n.tsx` (`wa.*` keys) so the two clients stay
/// in sync. A handful of extra `wa.promotion.*` / `wa.common.*` keys cover
/// strings the Webapp had hardcoded inline instead of localizing.
enum AppLocale { uz, ru, ar, en }

extension AppLocaleLabel on AppLocale {
  String get code => switch (this) {
        AppLocale.uz => 'uz',
        AppLocale.ru => 'ru',
        AppLocale.ar => 'ar',
        AppLocale.en => 'en',
      };

  String get label => switch (this) {
        AppLocale.uz => "O'zbek",
        AppLocale.ru => 'Русский',
        AppLocale.ar => 'العربية',
        AppLocale.en => 'English',
      };

  bool get isRtl => this == AppLocale.ar;

  static AppLocale fromCode(String? code) => switch (code) {
        'ru' => AppLocale.ru,
        'ar' => AppLocale.ar,
        'en' => AppLocale.en,
        _ => AppLocale.uz,
      };
}

